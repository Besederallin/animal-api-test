-- Works on both PostgreSQL and H2 (H2 runs in PostgreSQL compatibility mode).
CREATE TABLE picture (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    animal_type  VARCHAR(16)              NOT NULL CHECK (animal_type IN ('DUCK', 'DOG', 'BEAR')),
    content_type VARCHAR(100)             NOT NULL,
    size_bytes   INTEGER                  NOT NULL,
    source_url   VARCHAR(2048)            NOT NULL,
    image_data   BYTEA                    NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Makes "latest picture of an animal" a single index lookup.
CREATE INDEX idx_picture_animal_latest ON picture (animal_type, created_at DESC, id DESC);
